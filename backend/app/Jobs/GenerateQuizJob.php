<?php

namespace App\Jobs;

use App\Models\LearningObjectGenerationRun;
use App\Models\Quiz;
use App\Services\RagService;
use App\Services\RagServiceException;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Bus\Dispatchable;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Queue\SerializesModels;
use Illuminate\Support\Facades\DB;
use Throwable;

class GenerateQuizJob implements ShouldQueue
{
    use Dispatchable, InteractsWithQueue, Queueable, SerializesModels;

    public int $tries = 1;
    // Whole-document synthesis may span multiple cached map calls before final generation.
    public int $timeout = 1800;
    public bool $failOnTimeout = true;

    public function __construct(public int $runId)
    {
        // Quiz generation is interactive work and must never wait behind long document ingestion jobs.
        $this->onQueue('generation');
    }

    public function handle(RagService $rag): void
    {
        $run = LearningObjectGenerationRun::with('learningObject.course')->findOrFail($this->runId);
        if ($run->status !== 'queued') {
            return;
        }

        $run->update([
            'status' => 'generating',
            'started_at' => now(),
            'error_code' => null,
            'error_message' => null,
        ]);

        try {
            $generated = $rag->generateQuiz($run->learningObject->course, $run->generation_params);
            $this->persistResult($run, $generated);
        } catch (RagServiceException $exception) {
            $this->markFailed(
                $run,
                $exception->generationRunCode(),
                $exception->generationUserMessage('Quiz')
            );
        } catch (Throwable $exception) {
            report($exception);
            $this->markFailed($run, 'GENERATION_FAILED', 'Chưa thể tạo Quiz lúc này. Vui lòng thử lại sau.');
        }
    }

    private function persistResult(LearningObjectGenerationRun $run, array $generated): void
    {
        $payload = $generated['quiz'] ?? null;
        if (!is_array($payload) || empty($payload['questions']) || !is_array($payload['questions'])) {
            throw new \RuntimeException('AI service returned an incomplete quiz result.');
        }

        DB::transaction(function () use ($run, $payload) {
            $lockedRun = LearningObjectGenerationRun::lockForUpdate()->findOrFail($run->id);
            if ($lockedRun->status !== 'generating') {
                return;
            }

            $parameters = $lockedRun->generation_params;
            $object = $lockedRun->learningObject()->lockForUpdate()->firstOrFail();
            $title = $parameters['requested_title'] ?: $payload['title'];
            $description = $parameters['requested_description'] ?: ($payload['description'] ?? null);

            if ($object->status === 'draft' && !$object->versions()->exists()) {
                $object->update(['title' => $title, 'description' => $description]);
            }

            $snapshot = $this->generatedSnapshot($payload, $parameters);

            $version = $object->versions()->create([
                'version_number' => ((int) $object->versions()->max('version_number')) + 1,
                'payload' => $snapshot,
                'prompt' => collect($parameters)->except(['requested_title', 'requested_description', 'time_limit_minutes', 'passing_score', 'passing_percentage'])->all(),
                'change_summary' => 'Generated by AI',
                'created_by' => $object->created_by,
            ]);

            if (!$object->quiz()->exists()) {
                $quiz = $object->quiz()->create([
                    'question_count' => count($payload['questions']),
                    'time_limit_minutes' => $snapshot['time_limit_minutes'],
                    'passing_percentage' => $snapshot['passing_percentage'],
                ]);
                $this->replaceQuestions($quiz, $payload['questions'], $parameters['difficulty'] ?? 'medium');
            }

            $lockedRun->update(['status' => 'completed', 'finished_at' => now()]);
        });
    }

    private function replaceQuestions(Quiz $quiz, array $questions, string $defaultDifficulty = 'medium'): void
    {
        foreach (array_values($questions) as $questionIndex => $questionData) {
            $question = $quiz->questions()->create([
                'order_index' => $questionIndex,
                'question_text' => $questionData['question_text'] ?? $questionData['question'],
                'question_type' => 'single_choice',
                'difficulty' => $questionData['difficulty'] ?? $defaultDifficulty,
                'explanation' => $questionData['explanation'],
                'citation_metadata' => $questionData['citations'] ?? $questionData['citation_metadata'] ?? null,
            ]);
            foreach (array_values($questionData['options']) as $optionIndex => $optionText) {
                $question->options()->create([
                    'order_index' => $optionIndex,
                    'option_text' => $optionText,
                    'is_correct' => $optionIndex === (int) $questionData['correct_index'],
                ]);
            }
        }
    }

    private function contentSnapshot(Quiz $quiz): array
    {
        return [
            'question_count' => $quiz->question_count,
            'time_limit_minutes' => $quiz->time_limit_minutes,
            'passing_percentage' => $quiz->passing_percentage,
            'questions' => $quiz->questions->map(fn ($question) => [
                'order_index' => $question->order_index,
                'question_text' => $question->question_text,
                'question_type' => $question->question_type,
                'difficulty' => $question->difficulty,
                'explanation' => $question->explanation,
                'citation_metadata' => $question->citation_metadata,
                'options' => $question->options->map(fn ($option) => [
                    'order_index' => $option->order_index,
                    'option_text' => $option->option_text,
                    'is_correct' => $option->is_correct,
                ])->values()->all(),
            ])->values()->all(),
        ];
    }

    private function generatedSnapshot(array $payload, array $parameters): array
    {
        return [
            'time_limit_minutes' => $parameters['time_limit_minutes'] ?? null,
            'passing_percentage' => $parameters['passing_percentage'] ?? $parameters['passing_score'] ?? 60,
            'questions' => collect($payload['questions'])->values()->map(fn ($question, $index) => [
                'order_index' => $index,
                'question_text' => $question['question_text'] ?? $question['question'],
                'question_type' => 'single_choice',
                'difficulty' => $question['difficulty'] ?? ($parameters['difficulty'] ?? 'medium'),
                'explanation' => $question['explanation'],
                'citation_metadata' => $question['citations'] ?? $question['citation_metadata'] ?? null,
                'options' => collect(array_values($question['options']))->map(fn ($text, $optionIndex) => [
                    'order_index' => $optionIndex,
                    'option_text' => $text,
                    'is_correct' => $optionIndex === (int) $question['correct_index'],
                ])->all(),
            ])->all(),
        ];
    }

    private function markFailed(LearningObjectGenerationRun $run, string $code, string $message): void
    {
        $run->update([
            'status' => 'failed',
            'error_code' => $code,
            'error_message' => $message,
            'finished_at' => now(),
        ]);
    }

    public function failed(?Throwable $exception): void
    {
        $run = LearningObjectGenerationRun::find($this->runId);
        if ($run && in_array($run->status, ['queued', 'generating'], true)) {
            $this->markFailed($run, 'GENERATION_TIMEOUT', 'Quá trình tạo Quiz mất quá nhiều thời gian. Vui lòng thử lại.');
        }
    }
}
